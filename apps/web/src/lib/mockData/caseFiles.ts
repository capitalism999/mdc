function person(
  id: string,
  title: string,
  initials: string,
  color: string,
  sub: string,
  status: string,
  tone: CaseTone,
  date: string,
  info: [string, string][],
  note: string,
): CaseTreeItem {
  return { id, kind: 'person', title, initials, color, sub, status, tone, date, info, note }
}

function item(
  id: string,
  kind: CaseTreeItem['kind'],
  title: string,
  sub: string,
  status: string,
  tone: CaseTone,
  date: string,
  info: [string, string][],
  note: string,
  chain?: [string, string][],
): CaseTreeItem {
  return { id, kind, title, sub, status, tone, date, info, note, chain }
}

const PLACE_TYPES: Record<CasePlaceType, string> = {
  crime: 'Место преступления',
  home: 'Жильё',
  find: 'Находка',
  seen: 'Замечен',
  witness: 'Показания',
  other: 'Другое',
}

function place(
  id: string,
  title: string,
  sub: string,
  placeType: CasePlaceType,
  date: string,
  info: [string, string][],
  note: string,
  px: number,
  py: number,
): CaseTreeItem {
  return { ...item(id, 'place', title, sub, PLACE_TYPES[placeType], 'grey', date, [['Тип', PLACE_TYPES[placeType]], ...info], note), placeType, px, py }
}

function note(who: string, when: string, text: string, replies?: CaseNote[]): CaseNote {
  return { who, when, text, replies }
}

